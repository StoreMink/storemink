// ---------------------------------------------------------------------------
// The exemplar themes' own style rules (lib/themes/stylesheet.ts), one hand
// per design direction. They are plan Phase 3's exit evidence: the same
// renderer vocabulary, re-styled seven ways, each passing every gate, and
// each a reference for what a generated theme of that direction can reach.
//
// ★ Each is written as one designer's decisions (how names are set, how
//   things are framed, how they move), never a list of effects, and no two
//   share a hand: exemplars.test.ts holds every pair apart.
// ---------------------------------------------------------------------------

