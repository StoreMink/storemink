/** `withService` as the design review passes it (TS-3 fixer): one runner
 * that serves the reads and the photo run's claim and record, and counts the
 * transactions it has open. */
function runnerFor(
  caller: ReturnType<typeof callerDb>,
  run: ReturnType<typeof photoRun>,
) {
  const state = { open: 0, transactions: 0 };
  const runner = async <T>(work: (db: any) => Promise<T>): Promise<T> => {
    state.open += 1;
    state.transactions += 1;
    try {
      return await run.transaction((runDb) =>
        work({
          execute: (query: any) => {
            const { sql: text } = dialect.sqlToQuery(query);
            return text.includes("FOR UPDATE") ||
              text.includes("UPDATE theme_studio_runs")
              ? runDb.execute(query)
              : caller.db.execute(query);
          },
        }),
      );
    } finally {
      state.open -= 1;
    }
  };
  return { state, runner };
}

