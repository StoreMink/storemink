type Entry = Record<string, unknown>;

/** The image run that drew the photo, as the function's own transactions see
 * it: a locked read and a write, nothing else. */
function photoRun(entry: Entry, extra: Entry[] = []) {
  const state = {
    detail: {
      kind: "images",
      outcomes: [...extra, entry],
      anchorAssetId: ANCHOR,
    } as Entry,
    usage: { estimatedCostMicroUsd: 1_000, reviews: [] } as Entry,
    writes: 0,
    transactions: 0,
  };
  const db = {
    execute: async (query: any) => {
      const { sql: text, params } = dialect.sqlToQuery(query);
      if (text.includes("FOR UPDATE")) {
        expect(params).toEqual([RUN, PROJECT]);
        return {
          rows: [
            {
              detail: structuredClone(state.detail),
              usage: structuredClone(state.usage),
            },
          ],
        };
      }
      if (text.includes("UPDATE theme_studio_runs")) {
        state.detail = JSON.parse(params[0] as string);
        if (text.includes("usage="))
          state.usage = JSON.parse(params[1] as string);
        state.writes += 1;
        return { rows: [] };
      }
      throw new Error(`unexpected statement: ${text}`);
    },
  };
  return {
    state,
    entry: () => (state.detail.outcomes as Entry[])[extra.length],
    transaction: async <T>(work: (db: any) => Promise<T>): Promise<T> => {
      state.transactions += 1;
      return work(db);
    },
  };
}

/** The caller's transaction: the version, its photos, the bytes. */
function callerDb(opts: {
  pkg: ThemePackageV2;
  intent: ThemeIntent;
  rows: Entry[];
  held?: boolean;
  bytes?: Record<string, Buffer | null>;
}) {
  const statements: string[] = [];
  const db = {
    execute: vi.fn(async (query: any) => {
      const { sql: text, params } = dialect.sqlToQuery(query);
      statements.push(text);
      if (
        text.includes("FROM theme_studio_versions") &&
        !text.includes("RECURSIVE")
      )
        return {
          rows: [{ packageJson: opts.pkg, intentJson: opts.intent }],
        };
      if (text.includes("WITH RECURSIVE chain")) return { rows: opts.rows };
      if (text.includes("txid_current_if_assigned"))
        return { rows: [{ held: opts.held ?? false }] };
      if (text.includes("FROM theme_studio_assets")) {
        const key = String(params[1]);
        const bytes =
          opts.bytes && key in opts.bytes
            ? opts.bytes[key]
            : Buffer.from(`webp-${key}`);
        return { rows: bytes ? [{ bytes }] : [] };
      }
      if (text.trim() === "SELECT 1") return { rows: [] };
      throw new Error(`unexpected statement: ${text}`);
    }),
  };
  return { db: db as any, statements };
}

