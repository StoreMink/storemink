async function setup(entryExtra: Entry = {}) {
  const { pkg, intent, slot } = await theme();
  const entry: Entry = {
    slotId: slot.slotId,
    status: "generated",
    attempts: 2,
    review: "unreviewed",
    ...entryExtra,
  };
  const run = photoRun(entry);
  const row = {
    sha256: "a".repeat(64),
    review: entry.review,
    note: null,
    problems: null,
    runId: RUN,
    provider: "vertex-gemini",
    index: 0,
    sourceSlotId: slot.slotId,
    attempts: 2,
    recheck: entry.recheck ?? null,
    anchorAssetId: ANCHOR,
  };
  const caller = callerDb({ pkg, intent, rows: [row] });
  return { pkg, intent, slot, run, row, caller };
}

